// baseline-E/tools/gen-casefold.mjs — generator v1 (deterministic; dependency-free).
// Parses the authoritative Unicode 15.1.0 CaseFolding.txt and emits the pinned FULL case-fold table.
// Included statuses: C (common) + F (full). Excluded: S (simple-only; superseded by F for FULL folding), T (Turkic).
// Regeneration command: node baseline-E/tools/gen-casefold.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';

const SRC = 'baseline-E/data/CaseFolding-15.1.0.txt';
const OUT = 'baseline-E/src/casefold-table-15.1.0.mjs';
const GENERATOR_VERSION = 'casefold-gen-v1';

const text = readFileSync(SRC, 'utf8');
const srcSha = createHash('sha256').update(readFileSync(SRC)).digest('hex');
if (!/^# CaseFolding-15\.1\.0\.txt/.test(text)) { console.error('HARD STOP: source header is not CaseFolding-15.1.0'); process.exit(2); }

const table = {}; // srcCodePoint(decimal) -> [target code points]
let cCount = 0, fCount = 0, skipped = { S: 0, T: 0 };
for (const line of text.split('\n')) {
  const m = /^([0-9A-Fa-f]+);\s*([CFST]);\s*([0-9A-Fa-f ]+);/.exec(line);
  if (!m) continue;
  const status = m[2];
  if (status === 'S') { skipped.S++; continue; }
  if (status === 'T') { skipped.T++; continue; }
  const src = parseInt(m[1], 16);
  const targets = m[3].trim().split(/\s+/).map((h) => parseInt(h, 16));
  table[src] = targets;               // C and F only; F never coexists with C for the same source in the data
  if (status === 'C') cCount++; else fCount++;
}

// Deterministic serialization: sorted numeric keys.
const keys = Object.keys(table).map(Number).sort((a, b) => a - b);
const body = keys.map((k) => `  ${k}: [${table[k].join(',')}]`).join(',\n');
const tableSrc =
`// AUTO-GENERATED by ${GENERATOR_VERSION} from Unicode 15.1.0 CaseFolding.txt — DO NOT EDIT BY HAND.
// Source SHA-256: ${srcSha}
// Included statuses: C + F. Excluded: S (simple-only), T (Turkic). Full default case folding.
export const CASEFOLD_UNICODE_VERSION = '15.1.0';
export const CASEFOLD_SOURCE_SHA256 = '${srcSha}';
export const CASEFOLD_GENERATOR_VERSION = '${GENERATOR_VERSION}';
export const CASEFOLD_INCLUDED_STATUSES = ['C', 'F'];
export const CASEFOLD_EXCLUDED_STATUSES = ['S', 'T'];
export const CASEFOLD_TABLE = Object.freeze({
${body}
});
`;
writeFileSync(OUT, tableSrc);
const tableSha = createHash('sha256').update(readFileSync(OUT)).digest('hex');
console.log(JSON.stringify({ source_sha256: srcSha, out: OUT, generated_table_sha256: tableSha,
  c_entries: cCount, f_entries: fCount, skipped, total: keys.length, generator: GENERATOR_VERSION }, null, 2));
